func TestJSONStatus(t *testing.T) {
	for _, tc := range []struct {
		data string
		code int
	}{
		{`{}`, 0}, {`{"p":{"boundaryguard":[]}}`, 0},
		{`{"p":{"boundaryguard":[{"message":"BG001"}]}}`, 3},
		{`{"p":{"boundaryguard":{"error":"failed"}}}`, 1}, {`broken`, 1},
	} {
		if got := jsonStatus([]byte(tc.data)); got != tc.code {
			t.Errorf("%s: got %d want %d", tc.data, got, tc.code)
		}
	}
}

// Use real binaries and a local replace: tests never require network access.
func TestCLI(t *testing.T) {
	root, err := filepath.Abs(filepath.Join("..", ".."))
	if err != nil {
		t.Fatal(err)
	}
	bin := filepath.Join(t.TempDir(), "boundaryguard")
	if runtime.GOOS == "windows" {
		bin += ".exe"
	}
	build := exec.Command("go", "build", "-o", bin, "./cmd/boundaryguard")
	build.Dir = root
	if out, err := build.CombinedOutput(); err != nil {
		t.Fatalf("build: %v\n%s", err, out)
	}
	dir := t.TempDir()
	write := func(name, data string) {
		t.Helper()
		p := filepath.Join(dir, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(p), 0755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(data), 0644); err != nil {
			t.Fatal(err)
		}
	}
	write("go.mod", "module example.test/shop\n\ngo 1.26.0\n\nrequire external.test/lib v0.0.0\nreplace external.test/lib => ./external\n")
	write("external/go.mod", "module external.test/lib\ngo 1.26.0\n")
	write("external/lib.go", "package lib\nconst Value = 1\n")
	write("storage/storage.go", "package storage\nconst Value = 1\n")
	write("shared/shared.go", "package shared\nimport \"example.test/shop/storage\"\nconst Value = storage.Value\n")
	write("clean/clean.go", "package clean\nimport \"external.test/lib\"\nconst Value = lib.Value\n")
	write("domain/domain.go", "package domain\nimport \"example.test/shop/shared\"\nconst Value = shared.Value\n")
	write("direct/direct.go", "package direct\nimport _ \"example.test/shop/storage\"\n")
	write("generated/generated.go", "// Code generated by CLI fixture. DO NOT EDIT.\npackage generated\nimport \"log\"\nvar Stop = log.Fatal\n")
	write("tagged/base.go", "package tagged\n")
	write("tagged/tagged.go", "//go:build special\n\npackage tagged\nimport \"log\"\nvar Stop = log.Fatal\n")
	write("tests/base.go", "package tests\n")
	write("tests/internal_test.go", "package tests\nimport \"log\"\nvar Stop = log.Fatal\n")
	write("tests/external_test.go", "package tests_test\nimport \"log\"\nvar Stop = log.Fatal\n")
	write("broken/broken.go", "package broken\nvar X = doesNotExist\n")
	write("missing/missing.go", "package missing\nimport _ \"unavailable.invalid/missing\"\n")
	policy := `{"version":1,"layers":[{"name":"domain","packages":["example.test/shop/domain/...","example.test/shop/direct/..."]},{"name":"storage","packages":["example.test/shop/storage/..."]}],"dependency_rules":[{"id":"boundary","from_layer":"domain","to_layer":"storage","kind":"transitive"}],"forbidden_symbols":[{"id":"fatal","packages":["example.test/shop/..."],"symbol":"log.Fatal"}]}`
	write("policy.json", policy)
	write("bad.json", `{"version":1,"typo":true}`)
	write("empty.json", `{"version":1,"layers":[],"dependency_rules":[],"forbidden_symbols":[]}`)
	run := func(t *testing.T, want int, contains string, args ...string) string {
		t.Helper()
		cmd := exec.Command(bin, args...)
		cmd.Dir = dir
		cmd.Env = append(os.Environ(), "GOWORK=off", "GOPROXY=off")
		out, err := cmd.CombinedOutput()
		code := 0
		if err != nil {
			if ex, ok := err.(*exec.ExitError); ok {
				code = ex.ExitCode()
			} else {
				t.Fatal(err)
			}
		}
		if code != want {
			t.Fatalf("%v: exit %d want %d\n%s", args, code, want, out)
		}
		if contains != "" && !strings.Contains(string(out), contains) {
			t.Fatalf("%v: missing %q\n%s", args, contains, out)
		}
		return string(out)
	}
	for _, tc := range []struct {
		name     string
		args     []string
		code     int
		contains string
	}{
		{"help", []string{"-h"}, 0, "config"},
		{"missing config", []string{"./clean"}, 2, "-config is required"},
		{"no patterns", []string{"-config", "policy.json"}, 1, "Usage:"},
		{"bad path", []string{"-config", "absent.json", "./clean"}, 2, "absent.json"},
		{"bad json", []string{"-config", "bad.json", "./clean"}, 2, "unknown field"},
		{"unknown flag", []string{"-config", "policy.json", "-unknown", "./clean"}, 2, "flag"},
		{"fix rejected", []string{"-config", "policy.json", "-fix=1", "./domain"}, 2, "-fix is unsupported"},
		{"diff rejected", []string{"-config", "policy.json", "-diff", "./domain"}, 2, "-diff is unsupported"},
		{"clean replace", []string{"-config", "policy.json", "./clean"}, 0, ""},
		{"direct", []string{"-config", "policy.json", "./direct"}, 3, "BG001 [boundary]"},
		{"transitive", []string{"-config", "policy.json", "./domain"}, 3, "BG003 [boundary]"},
		{"generated", []string{"-config", "policy.json", "./generated"}, 3, "BG002 [fatal]"},
		{"default tags", []string{"-config", "policy.json", "./tagged"}, 0, ""},
		{"build tags", []string{"-config", "policy.json", "./tagged"}, 3, "BG002 [fatal]"},
		{"test variants", []string{"-config", "policy.json", "./tests"}, 3, "external_test.go"},
		{"exclude tests", []string{"-config", "policy.json", "-test=false", "./tests"}, 0, ""},
		{"compile error", []string{"-config", "policy.json", "./broken"}, 1, "doesNotExist"},
		{"dependency error", []string{"-config", "policy.json", "./missing"}, 1, "unavailable.invalid"},
		{"patterns", []string{"-config", "empty.json", "./clean/...", "./domain/..."}, 0, ""},
		{"json compile error", []string{"-config", "policy.json", "-json", "./broken"}, 1, "doesNotExist"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			if tc.name == "build tags" {
				t.Setenv("GOFLAGS", "-tags=special")
			}
			run(t, tc.code, tc.contains, tc.args...)
		})
	}
	jsonOut := run(t, 3, "BG003", "-config", "policy.json", "-json", "./domain")
	var native map[string]map[string]json.RawMessage
	if err := json.Unmarshal([]byte(jsonOut), &native); err != nil {
		t.Fatalf("native JSON: %v\n%s", err, jsonOut)
	}
	run(t, 0, "", "-config", "policy.json", "-json", "./clean")
	run(t, 3, "BG003", "-config", "policy.json", "-json=1", "./domain")
	run(t, 3, "BG003", "-config", "policy.json", "-json=TRUE", "./domain")
	run(t, 3, "BG003", "-config", "policy.json", "-json=1", "-json=0", "./domain")
	first := run(t, 3, "BG003", "-config", "policy.json", "./domain")
	second := run(t, 3, "BG003", "-config", "policy.json", "./domain")
	if first != second {
		t.Fatalf("unstable output:\n%s\n%s", first, second)
	}
	run(t, 0, "", "-config", "empty.json", "./domain")
	// Snapshot every source; a successful analysis must never rewrite it.
	snapshot := func() map[string][32]byte {
		m := map[string][32]byte{}
		err := filepath.WalkDir(dir, func(p string, d os.DirEntry, e error) error {
			if e != nil {
				return e
			}
			if !d.IsDir() && strings.HasSuffix(p, ".go") {
				b, e := os.ReadFile(p)
				if e != nil {
					return e
				}
				m[p] = sha256.Sum256(b)
			}
			return nil
		})
		if err != nil {
			t.Fatal(err)
		}
		return m
	}
	before := snapshot()
	run(t, 0, "", "-config", "empty.json", "./clean")
	after := snapshot()
	if len(before) != len(after) {
		t.Fatal("source set changed")
	}
	for p, h := range before {
		if after[p] != h {
			t.Fatalf("modified %s", p)
		}
	}
}
